PPR_ORDER = ['pStyle', 'keepNext', 'keepLines', 'pageBreakBefore', 'framePr', 'widowControl', 'numPr', 'suppressLineNumbers', 'pBdr', 'shd', 'tabs', 'suppressAutoHyphens', 'kinsoku', 'wordWrap', 'overflowPunct', 'topLinePunct', 'autoSpaceDE', 'autoSpaceDN', 'bidi', 'adjustRightInd', 'snapToGrid', 'spacing', 'ind', 'contextualSpacing', 'mirrorIndents', 'suppressOverlap', 'jc', 'textDirection', 'textAlignment', 'textboxTightWrap', 'outlineLvl', 'divId', 'cnfStyle', 'rPr', 'sectPr', 'pPrChange']
RPR_ORDER = ['rStyle', 'rFonts', 'b', 'bCs', 'i', 'iCs', 'caps', 'smallCaps', 'strike', 'dstrike', 'outline', 'shadow', 'emboss', 'imprint', 'noProof', 'snapToGrid', 'color', 'spacing', 'w', 'kern', 'position', 'sz', 'szCs', 'highlight', 'u', 'effect', 'bdr', 'shd', 'fitText', 'vertAlign', 'rtl', 'cs', 'em', 'lang', 'eastAsianLayout', 'specVanish', 'oMath', 'rPrChange']

def enforce_xml_order(element, order_list):
    children = list(element)
    def get_order(child):
        tag = child.tag.split('}')[-1]
        return order_list.index(tag) if tag in order_list else 999
    children.sort(key=get_order)
    for child in children:
        element.append(child)

def generate_word_reference():
    print("Generating Word DOCX reference...")
    ref_path = "custom-reference.docx"
    subprocess.run(["pandoc", "--print-default-data-file", "reference.docx"], stdout=open(ref_path, "wb"), check=True)
    doc = docx.Document(ref_path)

    for section in doc.sections:
        section.page_width = Inches(8.5)
        section.page_height = Inches(11.0)
        section.top_margin, section.bottom_margin, section.left_margin, section.right_margin = [Inches(1.0)] * 4

        # Enable different first page so headers/footers start on page 2 (matching Typst)
        section.different_first_page_header_footer = True

        # Header (Pages 2+)
        header = section.header
        hp = header.paragraphs[0]
        hp.alignment = WD_ALIGN_PARAGRAPH.LEFT
        hrun = hp.add_run()
        hrun.font.name = FONT_PRIMARY
        hrun.font.size = Pt(SIZE_FOOTNOTE)
        hrun.font.color.rgb = RGBColor.from_string(get_rgb(COLOR_FOOTNOTE))

        # Inject Word TITLE field code
        fld_begin = parse_xml(r'<w:fldChar %s w:fldCharType="begin"/>' % nsdecls('w'))
        instr_text = parse_xml(r'<w:instrText %s xml:space="preserve"> TITLE </w:instrText>' % nsdecls('w'))
        fld_sep = parse_xml(r'<w:fldChar %s w:fldCharType="separate"/>' % nsdecls('w'))
        fld_end = parse_xml(r'<w:fldChar %s w:fldCharType="end"/>' % nsdecls('w'))
        hrun._r.extend([fld_begin, instr_text, fld_sep, fld_end])

        # Footer (Pages 2+)
        footer = section.footer
        fp = footer.paragraphs[0]
        fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        frun = fp.add_run()
        frun.font.name = FONT_PRIMARY
        frun.font.size = Pt(SIZE_FOOTNOTE)
        frun.font.color.rgb = RGBColor.from_string(get_rgb(COLOR_FOOTNOTE))

        # Inject Word PAGE field code
        fld_begin_f = parse_xml(r'<w:fldChar %s w:fldCharType="begin"/>' % nsdecls('w'))
        instr_text_f = parse_xml(r'<w:instrText %s xml:space="preserve"> PAGE </w:instrText>' % nsdecls('w'))
        fld_sep_f = parse_xml(r'<w:fldChar %s w:fldCharType="separate"/>' % nsdecls('w'))
        fld_end_f = parse_xml(r'<w:fldChar %s w:fldCharType="end"/>' % nsdecls('w'))
        frun._r.extend([fld_begin_f, instr_text_f, fld_sep_f, fld_end_f])

    styles = doc.styles

    # ==========================================
    # HELPER: Safely get or create missing styles
    # ==========================================
    def get_or_add_style(name, style_type=WD_STYLE_TYPE.PARAGRAPH):
        try:
            return styles[name]
        except KeyError:
            return styles.add_style(name, style_type)

    try:
        doc_defaults = doc.styles.element.xpath('//w:docDefaults/w:rPrDefault/w:rPr')[0]
        rFonts_def = parse_xml(f'<w:rFonts {nsdecls("w")} w:ascii="{FONT_PRIMARY}" w:hAnsi="{FONT_PRIMARY}" w:cs="{FONT_PRIMARY}" w:eastAsia="{FONT_PRIMARY}"/>')
        doc_defaults.append(rFonts_def)
    except IndexError:
        pass

    def set_font(style, name=FONT_PRIMARY, size_pt=SIZE_BODY, color_hex=None, bold=False):
        if color_hex is None:
            color_hex = get_rgb(COLOR_TEXT)
        font = style.font
        font.name = name
        font.size = Pt(size_pt)
        font.color.rgb = RGBColor.from_string(color_hex)
        font.bold = bold
        rPr = style._element.get_or_add_rPr()
        rFonts = parse_xml(f'<w:rFonts {nsdecls("w")} w:ascii="{name}" w:hAnsi="{name}" w:cs="{name}" w:eastAsia="{name}"/>')
        rPr.append(rFonts)
        enforce_xml_order(rPr, RPR_ORDER)

    def add_background_and_borders(style, bg_hex, border_xml_str):
        pPr = style._element.get_or_add_pPr()
        for tag in ['shd', 'pBdr']:
            for child in pPr.xpath(f'w:{tag}'):
                pPr.remove(child)

        pPr.append(parse_xml(border_xml_str))
        pPr.append(parse_xml(f'<w:shd {nsdecls("w")} w:val="clear" w:color="auto" w:fill="{bg_hex}"/>'))
        enforce_xml_order(pPr, PPR_ORDER)

    # Base Document Styles
    normal = get_or_add_style('Normal')
    set_font(normal, FONT_PRIMARY, SIZE_BODY, get_rgb(COLOR_TEXT))
    normal.paragraph_format.space_after = Pt(SPACE_PARAGRAPH_AFTER_ODT)
    normal.paragraph_format.line_spacing = 1.15

    title = get_or_add_style('Title')
    set_font(title, FONT_PRIMARY, SIZE_TITLE, get_rgb(COLOR_TITLE), bold=True)
    title.paragraph_format.space_before, title.paragraph_format.space_after = Pt(SPACE_TITLE_BEFORE), Pt(SPACE_PARAGRAPH_AFTER_ODT)
    title.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER

    subtitle = get_or_add_style('Subtitle')
    set_font(subtitle, FONT_PRIMARY, SIZE_SUBTITLE, get_rgb(COLOR_TEXT), bold=False)
    subtitle.paragraph_format.space_before = Pt(SPACE_SUBTITLE_BEFORE_ODT)
    subtitle.paragraph_format.space_after = Pt(SPACE_SUBTITLE_AFTER_ODT)
    subtitle.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER

    author_style = get_or_add_style('Author')
    set_font(author_style, FONT_PRIMARY, SIZE_AUTHOR, get_rgb(COLOR_AUTHOR))
    author_style.paragraph_format.space_before = Pt(SPACE_AUTHOR_BEFORE_ODT)
    author_style.paragraph_format.space_after = Pt(SPACE_AUTHOR_AFTER_ODT)
    author_style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER

    date_style = get_or_add_style('Date')
