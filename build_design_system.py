def update_odt_style(root, style_name, text_props=None, para_props=None):
    xpath_query = f"//style:style[@style:name='{style_name}']"
    styles = root.xpath(xpath_query, namespaces=ODT_NAMESPACES)
    if not styles: return
    style_elem = styles[0]

    if text_props:
        t_elem = style_elem.find('style:text-properties', namespaces=ODT_NAMESPACES)
        if t_elem is None:
            t_elem = etree.SubElement(style_elem, f"{{{ODT_NAMESPACES['style']}}}text-properties")
        for key, val in text_props.items():
            if key == 'font-name':
                t_elem.set(f"{{{ODT_NAMESPACES['style']}}}font-name", val)
                t_elem.set(f"{{{ODT_NAMESPACES['fo']}}}font-family", f"'{val}'")
            elif key in ['color', 'font-size', 'font-weight', 'font-style', 'background-color', 'padding', 'padding-top', 'padding-bottom', 'padding-left', 'padding-right','border']:
                t_elem.set(f"{{{ODT_NAMESPACES['fo']}}}{key}", str(val))
            else:
                t_elem.set(f"{{{ODT_NAMESPACES['style']}}}{key}", str(val))

    if para_props:
        p_elem = style_elem.find('style:paragraph-properties', namespaces=ODT_NAMESPACES)
        if p_elem is None:
            p_elem = etree.SubElement(style_elem, f"{{{ODT_NAMESPACES['style']}}}paragraph-properties")
            
        fo_keys = {
            'break-before', 'break-after', 'keep-with-next', 'margin-top', 
            'margin-bottom', 'margin-left', 'margin-right', 'text-indent', 
            'text-align', 'line-height', 'background-color', 'border-left', 
            'border-top', 'border-bottom', 'border-right', 'border', 'padding', 
            'padding-top', 'padding-bottom', 'padding-left', 'padding-right'
        }

        if 'border' in para_props:
            for side in ['border-left', 'border-right', 'border-top', 'border-bottom']:
                side_qname = f"{{{ODT_NAMESPACES['fo']}}}{side}"
                if side_qname in p_elem.attrib:
                    del p_elem.attrib[side_qname]

        for key, val in para_props.items():
            if key in fo_keys:
                p_elem.set(f"{{{ODT_NAMESPACES['fo']}}}{key}", str(val))
            else:
                p_elem.set(f"{{{ODT_NAMESPACES['style']}}}{key}", str(val))


