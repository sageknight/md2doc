# Color helper functions
def get_hex(color_str):
    """Return '#RRGGBB' for CSS, SVG, ODT attributes."""
    return f"#{color_str.lstrip('#')}"

def get_rgb(color_str):
    """Return 'RRGGBB' (no '#') for DOCX XML and python-docx."""
    return color_str.lstrip('#')

